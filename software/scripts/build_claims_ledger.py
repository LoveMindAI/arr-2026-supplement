#!/usr/bin/env python3
"""Claims ledger for the numbers check (the original analysis + a reviewer). Every number-bearing sentence in the main text (sections 00-08, LaTeX
comments stripped), each number with the FACTS_v1 rows whose value matches it as printed (same matching as check_numbers.py:
leading zero optional, commas, rounding to 1-3 decimals). A match is a CANDIDATE source, not proof: the reviewer confirms the
row is the right one and that the sentence says what the number means. Appendix sections are listed too (lower priority; most
carry v3 numbers unchanged). Writes REVIEW_PACKET_<date>/CLAIMS_LEDGER.md. Usage: python3 scripts/build_claims_ledger.py OUTDIR"""
import glob, os, re, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = sys.argv[1]
norm = lambda x: x.replace(",", "").lstrip("+").rstrip(".")
def forms(x):
    x = norm(x); s = {x}
    if x.startswith("."): s.add("0" + x)
    if x.startswith("-."): s.add("-0" + x[1:])
    if x.startswith("0."): s.add(x[1:])
    if x.startswith("-0."): s.add("-" + x[2:])
    try:
        v = float(x)
        for d in (1, 2, 3):
            r = f"{v:.{d}f}"; s |= {r, r.replace("0.", ".", 1) if r.startswith("0.") else r, r.replace("-0.", "-.", 1)}
    except ValueError: pass
    return s
# index FACTS rows: every number inside a row's value cell points back to the row
index, section = {}, ""
for line in open(os.path.join(ROOT, "paper_notes", "FACTS_v1.md")):
    if line.startswith("## "): section = line[3:].strip(); continue
    if not line.startswith("| ") or line.startswith("| fact") or line.startswith("|---"): continue
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    if len(cells) < 3: continue
    fact, value, source = cells[0], " | ".join(cells[1:-1]), cells[-1].strip("`")
    for m in re.finditer(r"(?<![\w.])(-?\d[\d,]*(?:\.\d+)?|-?\.\d+)(?![\w])", value):
        for f in forms(m.group(1)):
            index.setdefault(f, []).append((section, fact, value[:90], source))
SKIP = {str(i) for i in range(10)}
MACROS = dict(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", open(os.path.join(ROOT, "paper", "results_macros.tex")).read()))
def clean(txt):
    txt = "\n".join(re.sub(r"(?<!\\)%.*", "", l) for l in txt.splitlines())   # only unescaped % starts a comment
    for name, val in MACROS.items(): txt = txt.replace("\\" + name + "{}", val).replace("\\" + name + " ", val + " ")
    txt = re.sub(r"\\(ref|label|cite[pt]?|citealp|includegraphics|input|VerbatimInput|url)\*?(\[[^\]]*\])*\{[^}]*\}", "", txt)
    txt = re.sub(r"\\(emph|textbf|textit|paragraph|section|subsection|caption|item)\*?(\[[^\]]*\])?", "", txt)
    return re.sub(r"[{}$~\\]", " ", txt)
rows, n_claim, n_num, n_unmatched = [], 0, 0, 0
files = sorted(glob.glob(os.path.join(ROOT, "paper", "sections", "0[0-8]*.tex"))) + \
        [os.path.join(ROOT, "paper", "sections", f) for f in ("app_escs.tex", "app_records.tex", "app_portraits.tex", "app_external.tex", "controlled_results_appendix.tex", "09_appendix.tex")] + \
        sorted(glob.glob(os.path.join(ROOT, "paper", "tab_*.tex")))
for f in files:
    part = "MAIN" if re.match(r"0[0-8]", os.path.basename(f)) else "APPENDIX"
    for sent in re.split(r"(?<=[.;:])\s+(?=[A-Z(])", clean(open(f).read())):
        sent = re.sub(r"\s+", " ", sent).strip()
        nums = [m.group(1) for m in re.finditer(r"(?<![\w.])(-?\d[\d,]*(?:\.\d+)?|-?\.\d+)(?![\w])", sent) if norm(m.group(1)) not in SKIP]
        if not nums: continue
        n_claim += 1; cid = f"{'M' if part == 'MAIN' else 'A'}{n_claim:03d}"
        lines = []
        for x in nums:
            n_num += 1
            hits = index.get(norm(x), [])
            seen, uniq = set(), []
            for h in hits:
                if (h[1], h[3]) not in seen: seen.add((h[1], h[3])); uniq.append(h)
            if not uniq: n_unmatched += 1
            src = "; ".join(f"[{h[0][:30]}] {h[1][:40]} = {h[2][:40]} ← `{h[3][:120]}`" for h in uniq[:3]) or "**no FACTS row as printed** (name/version/count/legal text, or trace by hand)"
            more = f" (+{len(uniq) - 3} more rows)" if len(uniq) > 3 else ""
            lines.append(f"  - `{x}` → {src}{more}")
        rows.append((part, cid, os.path.basename(f), sent, lines))
with open(os.path.join(OUT, "CLAIMS_LEDGER.md"), "w") as o:
    o.write("# Claims ledger: every number-bearing sentence, with candidate FACTS_v1 sources\n")
    o.write("Generated by `scripts/build_claims_ledger.py` from the current `paper/sections/` (LaTeX comments stripped). "
            "A FACTS match is a candidate, not proof: confirm (1) the row is the right one, (2) the value matches its source file, "
            "(3) the sentence says what the number means (scope, population, direction, comparison).\n\n")
    o.write(f"{n_claim} sentences, {n_num} numbers, {n_unmatched} with no FACTS row as printed.\n\n")
    for part in ("MAIN", "APPENDIX"):
        o.write(f"## {'Main text (priority)' if part == 'MAIN' else 'Appendix (most numbers carried from v3 unchanged)'}\n\n")
        for p, cid, fn, sent, lines in rows:
            if p != part: continue
            o.write(f"**{cid}** ({fn}) {sent}\n" + "\n".join(lines) + "\n\n")
print(f"{n_claim} sentences, {n_num} numbers, {n_unmatched} unmatched -> {OUT}/CLAIMS_LEDGER.md")
